/**
 * TDengine REST executor used independently for hot and statistics clusters.
 * @module @deepseek-ai/dsh-nilm-source/tdengine
 */

import {
  assertHttpEndpoint,
  NilmSourceError,
  readBoundedResponseText,
  ResponseLimitError,
} from '@deepseek-ai/dsh-nilm-core'

/** TDengine REST result rows are bounded before JSON parsing. */
const MAX_TDENGINE_RESPONSE_BYTES = 8 * 1024 * 1024

/** Minimal query surface for one TDengine endpoint. */
export interface TdengineExecutor {
  /**
   * Execute one internally generated statement.
   * @param sql - TDengine SQL text.
   * @param signal - caller cancellation combined with the transport timeout.
   * @returns rows keyed by column name.
   */
  query<T>(sql: string, signal?: AbortSignal): Promise<T[]>
}

interface TdengineResponse {
  code?: number
  desc?: string
  column_meta?: Array<[string, string, number]>
  data?: unknown[][]
}

/** HTTP REST transport for one TDengine database URL. */
export class HttpTdengineExecutor implements TdengineExecutor {
  /**
   * @param url - endpoint including the target database, for example `.../rest/sql/tpim_system`.
   * @param timeoutMs - request timeout.
   * @param user - optional Basic-auth account.
   * @param password - optional Basic-auth password.
   */
  constructor(
    private readonly url: string,
    private readonly timeoutMs: number,
    private readonly user?: string,
    private readonly password?: string,
  ) {}

  /**
   * Execute one statement over the TDengine REST endpoint.
   * @param sql - statement generated by a fixed adapter template.
   * @returns rows keyed by `column_meta` names.
   */
  async query<T>(sql: string, signal?: AbortSignal): Promise<T[]> {
    try {
      assertHttpEndpoint(this.url, 'TDengine URL')
    } catch (error) {
      throw new NilmSourceError('INVALID_SOURCE_CONFIG', error instanceof Error ? error.message : 'TDengine URL is invalid', { cause: error })
    }
    const timeout = AbortSignal.timeout(this.timeoutMs)
    const combined = signal === undefined ? timeout : AbortSignal.any([signal, timeout])
    let response: Response
    try {
      response = await fetch(this.url, {
        method: 'POST',
        headers: {
          'content-type': 'text/plain; charset=utf-8',
          ...this.authorization(),
        },
        body: sql,
        signal: combined,
        redirect: 'manual',
      })
    } catch (error) {
      if (combined.aborted) {
        const reason = timeout.aborted
          ? `TDengine exceeded ${String(this.timeoutMs)} ms`
          : 'TDengine request was cancelled'
        throw new NilmSourceError('SOURCE_UNAVAILABLE', reason, { cause: error })
      }
      throw new NilmSourceError('SOURCE_UNAVAILABLE', 'TDengine request failed', { cause: error })
    }
    if (!response.ok) {
      throw new NilmSourceError('SOURCE_UNAVAILABLE', `TDengine returned HTTP ${response.status}`)
    }
    let payload: TdengineResponse
    try {
      const text = await readBoundedResponseText(response, MAX_TDENGINE_RESPONSE_BYTES)
      payload = JSON.parse(text) as TdengineResponse
    } catch (error) {
      if (error instanceof ResponseLimitError) {
        throw new NilmSourceError('SOURCE_UNAVAILABLE', 'TDengine response exceeds the configured size limit', { cause: error })
      }
      throw new NilmSourceError('SOURCE_UNAVAILABLE', 'TDengine returned invalid JSON', { cause: error })
    }
    if (payload.code !== undefined && payload.code !== 0) {
      throw new NilmSourceError('SOURCE_UNAVAILABLE', `TDengine error ${payload.code}: ${payload.desc ?? 'unknown'}`)
    }
    const columns = (payload.column_meta ?? []).map(meta => meta[0])
    return (payload.data ?? []).map((row) => {
      const record: Record<string, unknown> = {}
      row.forEach((value, index) => {
        const column = columns[index]
        if (column !== undefined) record[column] = value
      })
      return record as T
    })
  }

  /**
   * List the visible tables on this endpoint.
   * @returns table names.
   */
  async listTables(signal?: AbortSignal): Promise<string[]> {
    const rows = await this.query<Record<string, unknown>>('SHOW TABLES', signal)
    return rows.map(row => String(Object.values(row)[0] ?? '')).filter(name => name.length > 0)
  }

  private authorization(): Record<string, string> {
    if (this.user === undefined || this.password === undefined) return {}
    return { authorization: `Basic ${Buffer.from(`${this.user}:${this.password}`).toString('base64')}` }
  }
}
